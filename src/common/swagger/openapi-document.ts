import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { INestApplication } from '@nestjs/common';
import { DocumentBuilder, type OpenAPIObject, SwaggerModule } from '@nestjs/swagger';
import { dump } from 'js-yaml';
import { ErrorResponse } from '../errors/dto/error-response.dto';
import { errorResponseFor } from './error-responses';
import {
  API_DESCRIPTION,
  API_SERVERS,
  API_TAGS,
  API_TITLE,
  SECURITY_SCHEMES,
} from './swagger.constants';

/** The committed contract (design §19). `npm run contract` writes it; CI checks it is current. */
export const CONTRACT_FILE = join(__dirname, '..', '..', '..', 'contracts', 'openapi.yaml');

const PACKAGE_JSON = join(__dirname, '..', '..', '..', 'package.json');

function packageVersion(): string {
  const { version } = JSON.parse(readFileSync(PACKAGE_JSON, 'utf8')) as { version?: unknown };
  if (typeof version !== 'string') throw new Error('package.json has no version');
  return version;
}

/**
 * Builds the OpenAPI document from the app's controllers and DTOs. It depends on code only,
 * never on configuration, so every environment produces the same document.
 *
 * - Paths are relative to the `/api/v1` server, as in the contract agreed with the frontend.
 * - Operation ids are the controller method names (`getHealth`), and must be unique.
 * - `ErrorResponse` is registered once; every operation documents `500 INTERNAL`.
 */
export function buildOpenApiDocument(app: INestApplication): OpenAPIObject {
  const builder = new DocumentBuilder()
    .setOpenAPIVersion('3.0.3')
    .setTitle(API_TITLE)
    .setDescription(API_DESCRIPTION)
    .setVersion(packageVersion())
    .addBearerAuth(
      {
        type: 'http',
        scheme: 'bearer',
        bearerFormat: 'JWT',
        description: 'Customer access token (15 minutes), from customer sign-in or refresh.',
      },
      SECURITY_SCHEMES.customer,
    )
    .addBearerAuth(
      {
        type: 'http',
        scheme: 'bearer',
        bearerFormat: 'JWT',
        description: 'Staff access token (15 minutes), from staff sign-in or refresh.',
      },
      SECURITY_SCHEMES.staff,
    )
    .addGlobalResponse(errorResponseFor(500, ['INTERNAL']));
  for (const server of API_SERVERS) builder.addServer(server.url, server.description);
  for (const tag of API_TAGS) builder.addTag(tag.name, tag.description);

  const document = SwaggerModule.createDocument(app, builder.build(), {
    ignoreGlobalPrefix: true,
    extraModels: [ErrorResponse],
    operationIdFactory: (_controllerKey: string, methodKey: string) => methodKey,
  });
  // DocumentBuilder always adds an empty contact object; there is no contact to publish.
  if (document.info.contact && Object.keys(document.info.contact).length === 0) {
    delete document.info.contact;
  }
  assertUniqueOperationIds(document);
  return document;
}

/** Fails fast when two routes share an operation id: generated clients would collide. */
export function assertUniqueOperationIds(document: OpenAPIObject): void {
  const seen = new Map<string, string>();
  for (const [path, item] of Object.entries(document.paths)) {
    for (const [method, operation] of Object.entries(item)) {
      const { operationId } = (operation ?? {}) as { operationId?: unknown };
      if (typeof operationId !== 'string') continue;
      const route = `${method.toUpperCase()} ${path}`;
      const previous = seen.get(operationId);
      if (previous) {
        throw new Error(`Operation id "${operationId}" is used by both ${previous} and ${route}`);
      }
      seen.set(operationId, route);
    }
  }
}

/** The YAML written to `contracts/openapi.yaml`: deterministic, with no folded lines. */
export function renderOpenApiYaml(document: OpenAPIObject): string {
  // A JSON round trip drops undefined values, which YAML can't represent.
  const plain = JSON.parse(JSON.stringify(document)) as object;
  return (
    '# Generated by `npm run contract` from the NestJS code. Do not edit by hand.\n' +
    dump(plain, { lineWidth: -1, noRefs: true })
  );
}
