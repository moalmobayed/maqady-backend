/** The four daily slots of a theater, 13:30, 16:15, 19:00 and 21:45, with their movies. */
function slots(theater: string, movies: readonly string[]): SeedShowtimeSlot[] {
  return ['13:30', '16:15', '19:00', '21:45'].map((startTime, index) => ({
    theater,
    startTime,
    movie: movies[index]!,
  }));
}
